import React, { useState } from 'react';
import { Code, Check, Copy, ExternalLink, ShieldCheck, Send } from 'lucide-react';

export default function PayPalInspector({ disputes }) {
  const [copied, setCopied] = useState(false);
  const [selectedDisputeId, setSelectedDisputeId] = useState(disputes[0]?.dispute_id || '');
  const dispute = disputes.find((d) => d.dispute_id === selectedDisputeId) || disputes[0];

  const payload = dispute?.ai_state?.investigation_report?.paypal_payload_ready || {
    evidence_type: 'PROOF_OF_DELIVERY',
    evidence_info: {
      tracking_info: [
        {
          carrier_name: 'FEDEX',
          tracking_number: '948210389102381',
        },
      ],
    },
    notes: 'Formal merchant rebuttal generated by AegisPay AI under PayPal Seller Protection Policy...',
    item_tags: ['SELLER_PROTECTION_CLAIMED', 'CARRIER_GPS_VERIFIED', 'DELIVERY_CONFIRMED'],
  };

  const copyPayload = () => {
    navigator.clipboard.writeText(JSON.stringify(payload, null, 2));
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem' }}>
      {/* Top Banner */}
      <div
        style={{
          background: 'var(--glass-bg)',
          border: '1px solid var(--glass-border)',
          borderRadius: '14px',
          padding: '1.25rem 1.5rem',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          flexWrap: 'wrap',
          gap: '1rem',
        }}
      >
        <div>
          <h3 style={{ fontSize: '1.15rem', display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
            <Code size={18} style={{ color: 'var(--paypal-cyan)' }} />
            PayPal REST API Integration Inspector
          </h3>
          <p style={{ fontSize: '0.785rem', color: 'var(--text-secondary)' }}>
            Inspect the exact JSON payload compiled by Lex Agent and transmitted to the PayPal Customer Disputes API.
          </p>
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem' }}>
          <select
            value={selectedDisputeId}
            onChange={(e) => setSelectedDisputeId(e.target.value)}
            style={{
              background: 'var(--bg-card)',
              color: 'var(--text-primary)',
              border: '1px solid var(--border-subtle)',
              borderRadius: '8px',
              padding: '0.45rem 0.85rem',
              fontSize: '0.8rem',
              outline: 'none',
            }}
          >
            {disputes.map((d) => (
              <option key={d.dispute_id} value={d.dispute_id}>
                {d.dispute_id} — {d.transaction_details.item_title.substring(0, 24)}...
              </option>
            ))}
          </select>

          <button className="btn btn-secondary" onClick={copyPayload}>
            {copied ? <Check size={14} style={{ color: 'var(--emerald-400)' }} /> : <Copy size={14} />}
            <span>{copied ? 'Copied!' : 'Copy Payload'}</span>
          </button>
        </div>
      </div>

      {/* Endpoint Bar */}
      <div
        style={{
          background: '#0B1120',
          border: '1px solid var(--border-subtle)',
          borderRadius: '10px',
          padding: '0.75rem 1.25rem',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          fontFamily: 'var(--font-mono)',
          fontSize: '0.8rem',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem' }}>
          <span style={{ background: 'var(--paypal-blue)', color: 'white', fontWeight: 700, padding: '2px 8px', borderRadius: '4px', fontSize: '0.725rem' }}>
            POST
          </span>
          <span style={{ color: '#E2E8F0' }}>
            https://api-m.sandbox.paypal.com/v1/customer/disputes/{dispute?.dispute_id}/provide-evidence
          </span>
        </div>
        <span style={{ color: 'var(--text-muted)', fontSize: '0.725rem' }}>
          Headers: Authorization: Bearer &bull;&bull;&bull;&bull; | Content-Type: application/json
        </span>
      </div>

      {/* JSON Viewer */}
      <div
        style={{
          background: '#06090F',
          border: '1px solid var(--border-subtle)',
          borderRadius: '12px',
          padding: '1.25rem',
          fontFamily: 'var(--font-mono)',
          fontSize: '0.8rem',
          color: '#38BDF8',
          overflowX: 'auto',
          maxHeight: '440px',
        }}
      >
        <pre>{JSON.stringify(payload, null, 2)}</pre>
      </div>

      {/* PayPal Seller Protection Specs */}
      <div
        style={{
          background: 'rgba(0, 112, 186, 0.08)',
          border: '1px solid rgba(0, 112, 186, 0.25)',
          borderRadius: '12px',
          padding: '1rem 1.25rem',
          display: 'flex',
          alignItems: 'center',
          gap: '1rem',
        }}
      >
        <ShieldCheck size={28} style={{ color: 'var(--paypal-cyan)', flexShrink: 0 }} />
        <div style={{ fontSize: '0.785rem', color: '#E2E8F0', lineHeight: 1.5 }}>
          <strong>PayPal Seller Protection Compliance Rule Engine:</strong> AegisPay automatically formats tracking carriers according to PayPal's strict enum schema (FEDEX, UPS, USPS, DHL) and appends cryptographic GPS accuracy receipts to fulfill 100% of the evidence criteria required for seller reimbursement.
        </div>
      </div>
    </div>
  );
}
